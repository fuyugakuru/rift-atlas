create or replace function public.validate_player_build() returns trigger language plpgsql security definer set search_path='' as $$
declare primary_tree text;
begin
 if (select count(distinct x) from unnest(new.items) x)<>6 or (select count(*) from public.build_catalog where id=any(new.items) and kind='item' and enabled)<>6 then raise exception 'Choose six different catalogue items';end if;
 if (select count(*) from public.build_catalog where id=any(new.items) and is_boot)>1 then raise exception 'Only one pair of boots';end if;
 if cardinality(new.runes)=5 then
  if (select count(distinct x) from unnest(new.runes) x)<>5 or (select count(*) from public.build_catalog where id=any(new.runes) and kind='rune' and enabled)<>5 or not exists(select 1 from public.build_catalog where id=new.runes[1] and is_keystone) or (select count(*) from public.build_catalog where id=any(new.runes) and is_keystone)<>1 then raise exception 'Invalid rune page';end if;
  select rune_tree into primary_tree from public.build_catalog where id=new.runes[2] and rune_row=1;
  if primary_tree is null or not exists(select 1 from public.build_catalog where id=new.runes[3] and rune_tree=primary_tree and rune_row=2) or not exists(select 1 from public.build_catalog where id=new.runes[4] and rune_tree=primary_tree and rune_row=3) or not exists(select 1 from public.build_catalog where id=new.runes[5] and rune_tree<>primary_tree and rune_row is not null) then raise exception 'Invalid primary or secondary rune slots';end if;
 end if;
 new.updated_at=now();return new;
end $$;
