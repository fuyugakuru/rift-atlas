create table public.official_build_edits(
 champion text primary key references public.matchup_champion_catalog(id),
 value jsonb not null default '[]'::jsonb,
 revision bigint not null default 1,
 actor_id uuid not null references auth.users(id),
 updated_at timestamptz not null default clock_timestamp()
);
alter table public.official_build_edits enable row level security;
revoke all on public.official_build_edits from public,anon,authenticated;
create table public.official_build_history(
 id bigint generated always as identity primary key,
 champion text not null,
 before_value jsonb not null,
 after_value jsonb not null,
 actor_id uuid not null references auth.users(id),
 created_at timestamptz not null default clock_timestamp()
);
alter table public.official_build_history enable row level security;
revoke all on public.official_build_history from public,anon,authenticated;
create function public.official_build_get(p_champion text) returns jsonb language sql stable security definer set search_path='' as $$
 select coalesce((select jsonb_build_object('value',value,'revision',revision) from public.official_build_edits where champion=p_champion),jsonb_build_object('value','[]'::jsonb,'revision',0))
$$;
create function public.official_build_save(p_champion text,p_value jsonb,p_expected bigint) returns bigint language plpgsql security definer set search_path='' as $$
declare previous jsonb;version bigint;entry jsonb;
begin
 perform public.require_site_staff(true);
 if p_champion is null or not exists(select 1 from public.matchup_champion_catalog where id=p_champion) or p_value is null or jsonb_typeof(p_value)<>'array' or p_expected is null then raise exception 'Invalid build';end if;
 if jsonb_array_length(p_value)>500 or octet_length(p_value::text)>150000 then raise exception 'Invalid build';end if;
 for entry in select * from jsonb_array_elements(p_value) loop
  if jsonb_typeof(entry)<>'object' or not entry ?& array['slot','base','asset'] or (select count(*) from jsonb_object_keys(entry))<>3 then raise exception 'Invalid slot';end if;
  if entry->>'slot' !~ '^build-panel-[0-9]{1,2}:[0-9]{1,3}$' or jsonb_typeof(entry->'slot')<>'string' or jsonb_typeof(entry->'base')<>'string' or jsonb_typeof(entry->'asset')<>'string' or not exists(select 1 from public.official_build_asset_catalog where id=entry->>'asset') or not exists(select 1 from public.official_build_asset_catalog where id=entry->>'base') or split_part(entry->>'asset',':',1)<>split_part(entry->>'base',':',1) then raise exception 'Invalid replacement';end if;
 end loop;
 if (select count(distinct x->>'slot') from jsonb_array_elements(p_value)x)<>jsonb_array_length(p_value) then raise exception 'Duplicate slot';end if;
 perform pg_advisory_xact_lock(hashtextextended('official-build:'||p_champion,0));
 select value,revision into previous,version from public.official_build_edits where champion=p_champion for update;
 version:=coalesce(version,0);previous:=coalesce(previous,'[]'::jsonb);
 if version<>p_expected then raise exception 'Build changed. Reload first';end if;
 insert into public.official_build_edits(champion,value,revision,actor_id) values(p_champion,p_value,version+1,auth.uid()) on conflict(champion) do update set value=excluded.value,revision=excluded.revision,actor_id=excluded.actor_id,updated_at=clock_timestamp();
 insert into public.official_build_history(champion,before_value,after_value,actor_id) values(p_champion,previous,p_value,auth.uid());
 return version+1;
end $$;
revoke all on function public.official_build_get(text),public.official_build_save(text,jsonb,bigint) from public,anon,authenticated;
grant execute on function public.official_build_get(text) to anon,authenticated;
grant execute on function public.official_build_save(text,jsonb,bigint) to authenticated;
notify pgrst,'reload schema';
commit;
