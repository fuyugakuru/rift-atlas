create policy "Insert own player builds" on public.player_builds for insert to authenticated with check ((select auth.uid())=user_id);
create policy "Update own player builds" on public.player_builds for update to authenticated using ((select auth.uid())=user_id) with check ((select auth.uid())=user_id);
create policy "Delete own player builds" on public.player_builds for delete to authenticated using ((select auth.uid())=user_id);
create index if not exists player_builds_stats on public.player_builds(champion_id,lane,patch);
create or replace function public.validate_player_build() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if (select count(distinct x) from unnest(new.items) x)<>6 or
    (select count(*) from public.build_catalog where id=any(new.items) and kind='item')<>6 then
  raise exception 'Choose six different catalogue items';
 end if;
 if (select count(*) from public.build_catalog where id=any(new.items) and is_boot)>1 then raise exception 'Only one pair of boots'; end if;
 if cardinality(new.runes)=5 then
  if (select count(distinct x) from unnest(new.runes) x)<>5 or
     (select count(*) from public.build_catalog where id=any(new.runes) and kind='rune')<>5 or
     not exists(select 1 from public.build_catalog where id=new.runes[1] and is_keystone) or
     (select count(*) from public.build_catalog where id=any(new.runes) and is_keystone)<>1 then
   raise exception 'Invalid rune page';
  end if;
 end if;
 new.updated_at=now();return new;
end $$;
revoke all on function public.validate_player_build() from public,anon,authenticated;
create trigger validate_player_build before insert or update on public.player_builds for each row execute function public.validate_player_build();
create or replace function public.build_item_popularity(p_champion text,p_lane text,p_patch text)
returns table(item_id text,picks bigint,participants bigint,percentage numeric)
language sql stable security definer set search_path='' as $$
 with selected as (select items from public.player_builds where champion_id=p_champion and lane=p_lane and patch=p_patch),
 total as (select count(*) n from selected), counts as (select x item_id,count(*) picks from selected cross join lateral unnest(items) x group by x)
 select counts.item_id,counts.picks,total.n,round(100.0*counts.picks/nullif(total.n,0),1) from counts cross join total order by counts.picks desc,counts.item_id;
$$;
revoke all on function public.build_item_popularity(text,text,text) from public;
grant execute on function public.build_item_popularity(text,text,text) to anon,authenticated;
