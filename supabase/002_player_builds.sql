create table if not exists public.player_builds (
 user_id uuid not null references auth.users(id) on delete cascade,
 champion_id text not null references public.build_champions(id),
 lane text not null check(lane in ('baron','jungle','mid','dragon','support')),
 patch text not null check(patch ~ '^[0-9]{1,2}\.[0-9]{1,2}[a-z]?$'),
 items text[] not null check(cardinality(items)=6),
 runes text[] not null default '{}' check(cardinality(runes) in (0,5)),
 updated_at timestamptz not null default now(),
 primary key(user_id,champion_id,lane,patch)
);
alter table public.player_builds enable row level security;
revoke all on public.player_builds from anon,authenticated;
grant select,insert,update,delete on public.player_builds to authenticated;
